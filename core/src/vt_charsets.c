static int in_ranges(uint32_t cp, const uint32_t *r, int pairs)
{
	int lo = 0, hi = pairs - 1;
	while (lo <= hi) {
		int mid = (lo + hi) / 2;
		if (cp < r[mid * 2])
			hi = mid - 1;
		else if (cp > r[mid * 2 + 1])
			lo = mid + 1;
		else
			return 1;
	}
	return 0;
}

int wcwidth_of(uint32_t cp)
{
	if (cp < 0x300)
		return 1;
	if (in_ranges(cp, wc_zero, (int)(sizeof(wc_zero) / sizeof(wc_zero[0]) / 2)))
		return 0;
	if (in_ranges(cp, wc_wide, (int)(sizeof(wc_wide) / sizeof(wc_wide[0]) / 2)))
		return 2;
	return 1;
}
