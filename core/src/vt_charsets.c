int gset_by_designator(const char *d, int is96)
{
	int g, k;
	for (g = 0; g < G_COUNT; g++) {
		if (gsets[g].is96 != is96)
			continue;
		for (k = 0; k < 3; k++)
			if (gsets[g].designators[k] &&
			    strcmp(gsets[g].designators[k], d) == 0)
				return g;
	}
	return -1;
}

int gset_is96(int g)
{
	return gsets[g].is96;
}

int gset_level(int g)
{
	return gsets[g].level;
}

const char *gset_designator(int g)
{
	return gsets[g].designators[0] ? gsets[g].designators[0] : "";
}

/* where DEC Supplemental isn't Latin-1: ¤ at 0x28, Œ Ÿ œ ÿ, and the codes
   it left empty (shown blank) */
static uint32_t supplemental(uint32_t cp)
{
	switch (cp) {
	case 0x28: return 0xa4;
	case 0x57: return 0x152;
	case 0x5d: return 0x178;
	case 0x77: return 0x153;
	case 0x7d: return 0xff;
	case 0x24: case 0x26: case 0x2c: case 0x2d: case 0x2e: case 0x2f:
	case 0x34: case 0x38: case 0x3e: case 0x50: case 0x5e: case 0x70:
	case 0x7e:
		return 0x20;
	}
	return cp + 0x80;
}

uint32_t gset_map(int g, uint32_t cp)
{
	const uint32_t *t;
	switch (g) {
	case G_ASCII:
		return cp;
	case G_DEC_GRAPHICS:
		return dec_graphics(cp);
	case G_VT52_GRAPHICS:
		return cp >= 0x5e && cp <= 0x7e ? vt52_tab[cp - 0x5e] : cp;
	case G_DEC_SUPPLEMENTAL:
		return cp >= 0x21 && cp <= 0x7e ? supplemental(cp) : cp;
	case G_DEC_TECHNICAL:
		return cp >= 0x21 && cp <= 0x7e ? technical_tab[cp - 0x21] : cp;
	case G_LATIN1:
		return cp >= 0x20 && cp <= 0x7f ? cp + 0x80 : cp;
	}
	for (t = gsets[g].table; t && *t; t += 2)
		if (t[0] == cp)
			return t[1];
	return cp;
}

