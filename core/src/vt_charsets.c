uint32_t cp437_decode(int b)
{
	return b < 0x80 ? (uint32_t)b : cp437_high[(b - 0x80) & 0x7f];
}

int cp437_encode(uint32_t cp)
{
	int i;
	if (cp < 0x80)
		return (int)cp;
	for (i = 0; i < 128; i++)
		if (cp437_high[i] == cp)
			return 0x80 + i;
	return '?';
}

void charset_encode(int cs, const uint32_t *cps, int n, dmc_buf *out)
{
	int i;
	for (i = 0; i < n; i++) {
		uint32_t c = cps[i];
		if (cs == CS_UTF8)
			utf8_put(out, c);
		else if (cs == CS_LATIN1)
			buf_addc(out, (char)(c < 256 ? c : '?'));
		else
			buf_addc(out, (char)cp437_encode(c));
	}
}

uint32_t dec_graphics(uint32_t cp)
{
	return cp >= 0x5f && cp <= 0x7e ? dec_graphics_tab[cp - 0x5f] : cp;
}

